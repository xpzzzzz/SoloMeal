import test from 'node:test';
import assert from 'node:assert/strict';
import {addKindAndBatch,clickAction,desktopContext,horizontalOverflow,launchBrowser,makeApi,mobileContext,
 openPage,shot,signUp,startFixture,waitText} from './support.mjs';

for(const mobile of [false,true])test(`简洁界面保留录入、菜谱反馈、采购、做饭与助手入口（${mobile?'手机':'桌面'}）`,async()=>{
 const server=process.env.UI_PREVIEW_URL?{url:process.env.UI_PREVIEW_URL,stop:async()=>{}}:await startFixture(0,{recipeDiscovery:true,receiptParser:true});
 let browser;
 try{
  browser=await launchBrowser();
  const context=await (mobile?mobileContext:desktopContext)(browser);
  const page=await openPage(context,server.url);
  const username='comfort_'+(mobile?'mobile':'desktop')+(process.env.UI_PREVIEW_URL?'_'+Date.now().toString(36):'');
  const password='comfort-fixture-123';
  await signUp(page,username,password);
  const api=makeApi(server.url),token=await api.signIn(username,password);
  const primary=page.getByRole('navigation',{name:'主导航'});
  assert.deepEqual(await primary.getByRole('button').allInnerTexts(),['今天','食材库存','我的菜谱','报价与采购']);
  await primary.getByRole('button',{name:'食材库存',exact:true}).click();
  assert.equal(await page.locator('#inventory-entry').evaluate(el=>el.open),false,'库存以查看为主，录入按需展开');
  await page.getByRole('button',{name:'添加库存',exact:true}).click();
  await page.locator('#inventory-entry[open]').waitFor({state:'attached'});
  assert.equal(await page.locator('#inventory-entry').evaluate(el=>el.open),true);
  await addKindAndBatch(page,{name:'大米',unit:'g',quantity:'300',location:'常温'});
  assert.equal(await page.locator('input[name="quantity"]').getAttribute('step'),'0.001','保留原数量精度');
  await page.getByLabel('搜索食材').fill('不存在的食材');
  assert.equal(await page.locator('table tbody tr').count(),0);
  await page.getByLabel('搜索食材').fill('大米');
  assert.equal(await page.locator('table tbody tr').count(),1);
  await page.evaluate(()=>window.scrollTo(0,0));
  await shot(page,`comfort-${mobile?'mobile':'desktop'}-inventory.png`);
  await page.getByRole('navigation',{name:'库存功能'}).getByRole('button',{name:'小票录入',exact:true}).click();
  await page.getByRole('heading',{name:'拍张小票，记入厨房'}).waitFor();
  assert.equal(await page.getByRole('button',{name:'上传小票',exact:true}).count(),1);

  await page.getByRole('navigation',{name:'厨房工具'}).getByRole('button',{name:'厨房偏好',exact:true}).click();
  await page.getByLabel('现有厨具（逗号分隔）').fill('煮锅,炒锅');
  const savedPreferences=page.waitForResponse(r=>r.url().endsWith('/me/preferences')&&r.request().method()==='PUT');
  await page.getByRole('button',{name:'保存偏好',exact:true}).click();
  assert.equal((await savedPreferences).status(),200);
  await primary.getByRole('button',{name:'我的菜谱',exact:true}).click();
  assert.equal(await page.locator('#recipe-recommendations').evaluate(el=>el.open),false,'菜谱库默认不展开推荐参数');
  await page.getByRole('button',{name:'添加菜谱',exact:true}).click();
  const editor=page.locator('#recipe-editor');
  await editor.getByLabel('菜谱名称').fill('简洁界面米饭');
  await editor.getByLabel('厨具（逗号分隔）').fill('煮锅');
  await editor.getByLabel('做法（每行一步）').fill('洗米\n煮熟');
  await editor.getByRole('combobox').selectOption({label:'大米（克）'});
  await editor.getByLabel('数量',{exact:true}).fill('80');
  await editor.getByRole('button',{name:'保存菜谱',exact:true}).click();
  const card=page.locator('.recipe').filter({has:page.getByRole('heading',{name:'简洁界面米饭',exact:true})});
  await card.waitFor();
  assert.equal(await card.locator('.recipe-art svg').count(),1,'新增菜谱也采用完整卡片样式');
  assert.equal(await card.getByRole('button',{name:'编辑菜谱',exact:true}).count(),0,'次要操作默认折叠');
  await card.getByRole('button',{name:'喜欢',exact:true}).click();
  await waitText(page,/评价已保存/);
  await page.getByLabel('评价筛选').selectOption('like');
  assert.equal(await page.locator('.recipe').count(),1);
  await page.getByLabel('评价筛选').selectOption('dislike');
  assert.equal(await page.locator('.recipe').count(),0);
  await page.getByLabel('评价筛选').selectOption('all');
  await card.getByRole('button',{name:'不喜欢',exact:true}).click();
  await waitText(page,/评价已保存/);
  await card.getByRole('button',{name:'收藏',exact:true}).click();
  await waitText(page,/评价已保存/);
  await page.getByLabel('只看收藏').check();
  assert.equal(await page.locator('.recipe').count(),1);
  await page.getByLabel('只看收藏').uncheck();
  await clickAction(card,'加入采购组合');
  await page.locator('.combination-panel').waitFor();
  assert.equal(await page.getByLabel('人数 · 简洁界面米饭').inputValue(),'1');
  assert.equal(Number((await api.call(token,'/inventory')).data[0].quantity),300,'选菜与采购组合不扣库存');
  await page.getByRole('button',{name:'移出组合',exact:true}).click();
  await clickAction(card,'记录做完这道菜');
  await page.locator('.modal').getByRole('button',{name:'确认做完',exact:true}).click();
  await waitText(page,/已记录，库存同步更新/);
  assert.equal(Number((await api.call(token,'/inventory')).data[0].quantity),220);
  await page.getByRole('navigation',{name:'厨房工具'}).getByRole('button',{name:'用餐记录',exact:true}).click();
  const undone=page.waitForResponse(r=>r.url().endsWith('/undo')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'撤销并恢复食材',exact:true}).click();
  assert.equal((await undone).status(),200);
  assert.equal(Number((await api.call(token,'/inventory')).data[0].quantity),300,'撤销仍按实际消耗恢复');

  await primary.getByRole('button',{name:'我的菜谱',exact:true}).click();
  await page.getByRole('navigation',{name:'菜谱功能'}).getByRole('button',{name:'发现菜谱',exact:true}).click();
  await page.getByRole('heading',{name:'发现新菜谱',exact:true}).waitFor();
  await page.getByRole('button',{name:'生成候选',exact:true}).waitFor();
  await primary.getByRole('button',{name:'我的菜谱',exact:true}).click();
  await page.locator('.examples-panel>summary').click();
  await page.getByRole('button',{name:'导入示例菜谱',exact:true}).click();
  await waitText(page,/示例菜谱已就绪/);
  await page.evaluate(()=>window.scrollTo(0,0));
  await shot(page,`comfort-${mobile?'mobile':'desktop'}-recipes.png`);
  await primary.getByRole('button',{name:'今天',exact:true}).click();
  await page.locator('.home-recommendations .recommendation-card').first().waitFor();
  assert.ok(await horizontalOverflow(page)<=1,'首页不横向溢出');
  await page.evaluate(()=>window.scrollTo(0,0));
  await shot(page,`comfort-${mobile?'mobile':'desktop'}-today.png`);
  await page.getByRole('button',{name:'一人食助手',exact:true}).click();
  await page.getByRole('button',{name:'推荐20分钟内能做好的菜',exact:true}).click();
  assert.equal(await page.getByLabel('想安排怎样的一餐？').inputValue(),'推荐20分钟内能做好的菜');
  assert.equal(await page.locator('.technical-details').first().evaluate(el=>el.open),false,'技术记录保留为折叠入口');
  await page.evaluate(()=>window.scrollTo(0,0));
  await shot(page,`comfort-${mobile?'mobile':'desktop'}-assistant.png`);
  assert.ok(await horizontalOverflow(page)<=1,'助手不横向溢出');
  assert.equal((await api.call(token,'/agent/runs')).data.length,0,'点建议仅填入文本，不自动调用模型');
  assert.deepEqual(page.problems,[]);
  await context.close();
 }finally{if(browser)await browser.close();await server.stop();}
});
