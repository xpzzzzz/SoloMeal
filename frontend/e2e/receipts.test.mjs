test('窄屏小票显示单位冲突和确认失败，修正后只入库一次',async()=>{
 const user='ui_receipt_units';
 await api.call(null,'/auth/register','POST',{username:user,password:PASSWORD});
 const token=await api.signIn(user,PASSWORD);
 const ingredient=(await api.call(token,'/ingredients','POST',{name:'大米',unit:'g'})).data;
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,locale:'zh-CN'});
 try{
  const page=await openPage(context,server.url);
  await signIn(page,user,PASSWORD);
  await useTab(page,'小票录入');
  await page.getByLabel('小票图片').setInputFiles({name:'units.png',mimeType:'image/png',buffer:image});
  await page.getByRole('button',{name:'上传小票',exact:true}).click();
  await waitText(page,/小票已私有保存/);
  await page.getByRole('button',{name:'添加小票行'}).click();
  await page.getByLabel('小票名称').fill('测试大米');
  await page.getByLabel('对应食材').selectOption(ingredient.id);
  await page.getByLabel('数量（未知留空）').fill('7');
  await page.getByLabel('小票单位',{exact:true}).selectOption('piece');
  await page.getByLabel('仍需核对').uncheck();
  await page.getByRole('button',{name:'保存小票草稿'}).click();
  await waitText(page,/小票 · 版本 2/);
  const alert=page.locator('.purchase-line').getByRole('alert');
  assert.match(await alert.innerText(),/不能直接换算/);
  assert.equal(await page.getByRole('button',{name:'核对小票入库',exact:true}).isDisabled(),true);
  assert.deepEqual((await api.call(token,'/inventory')).data,[]);
  await page.getByLabel('数量（未知留空）').fill('0.7');
  await page.getByLabel('小票单位',{exact:true}).selectOption('kg');
  await page.getByRole('button',{name:'保存小票草稿'}).click();
  await waitText(page,/小票 · 版本 3/);
  await page.getByRole('button',{name:'核对小票入库',exact:true}).click();
  const saved=(await api.call(token,'/receipts')).data[0];
  const url=server.url+'/api/v1/receipts/'+saved.id+'/confirm';
  await page.route(url,route=>route.fulfill({status:422,contentType:'application/json',body:JSON.stringify({error:{code:'UNIT_AMBIGUOUS'}})}));
  await page.getByRole('button',{name:'确认小票并整单入库',exact:true}).click();
  const failure=page.locator('.receipt-editor').getByRole('alert');
  await failure.waitFor();
  assert.match(await failure.innerText(),/单位不能直接换算/);
  const box=await failure.boundingBox();
  assert.ok(box.y>=0&&box.y+box.height<=844,'错误应在点击后的手机视口内');
  assert.deepEqual((await api.call(token,'/inventory')).data,[]);
  await shot(page,'receipt-unit-failure-mobile.png');
  await page.unroute(url);
  await page.getByRole('button',{name:'确认小票并整单入库',exact:true}).click();
  await waitText(page,/小票已整单入库/);
  const stock=(await api.call(token,'/inventory')).data;
  assert.equal(stock.length,1);
  assert.equal(Number(stock[0].quantity),700);
  assert.equal((await api.call(token,'/inventory/events')).data.length,1);
 }finally{await context.close();}
});
